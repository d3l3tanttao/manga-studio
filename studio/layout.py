def label(text, role="muted"):
    w = QLabel(text)
    w.setObjectName(role)
    w.setWordWrap(True)
    return w


def button(text, slot, role="", tip=""):
    w = QPushButton(text)
    w.setObjectName(role)
    w.clicked.connect(slot)
    w.setToolTip(tip)
    return w


def panel(name):
    w = QFrame()
    w.setObjectName(name)
    return w


def panel_icon(left):
    image = QPixmap(36,36)
    image.fill(Qt.transparent)
    painter = QPainter(image)
    painter.setPen(QPen(QColor("#dfd2f2"), 2))
    painter.drawRoundedRect(3,6,29,24,3,3)
    painter.fillRect(6 if left else 22,9,8,18,QColor("#b99bdc"))
    painter.end()
    image.setDevicePixelRatio(2)
    return QIcon(image)


def row(layout, *widgets):
    r = QHBoxLayout()
    r.setSpacing(5)
    for w in widgets:
        r.addWidget(w)
    layout.addLayout(r)


def tab(tabs, name):
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    w = QWidget()
    w.setSizePolicy(QSizePolicy.Ignored,QSizePolicy.Preferred)
    scroll.setWidget(w)
    tabs.addTab(scroll, name)
    lay = QVBoxLayout(w)
    lay.setSizeConstraint(QLayout.SetNoConstraint)
    lay.setContentsMargins(9, 12, 9, 8)
    return lay


